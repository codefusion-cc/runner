//! What the supervisor decides as a container's first process before the job starts: the firewall's inputs, the
//! limits it checks are in force, the seccomp filter that keeps a job from user namespaces, and the look that
//! proves nothing the job could undo them with is left.

use cf_nft::{BLOCKED, IPV4, Packet, TCP, UDP, Verdict, decide};
use cf_supervisor::confine::{default_gateway, limits_in_force, locked_down, name_servers};
use cf_supervisor::firewall::{own_networks, policy};
use cf_supervisor::seccomp::{
    AARCH64, ARM, CLONE_NEWUSER, Data, I386, X32_BIT, X86_64, allow, no_user_namespaces, verdict,
};
use proptest::prelude::*;

fn out(rules: &[cf_nft::Rule], dest: [u8; 4], protocol: u8, dest_port: u16, loopback: bool) -> Verdict {
    let packet = Packet {
        ether_type: IPV4,
        in_interface: None,
        loopback,
        dest,
        protocol,
        dest_port,
        established: false,
    };
    decide(rules, Verdict::Accept, &packet)
}

#[test]
fn the_name_servers_are_the_ipv4_ones_the_engine_wrote() {
    let resolv = "# Generated by Podman\nsearch dns.podman\nnameserver 10.89.0.1\n\
                  nameserver fd00::1\n options edns0\nnameserver\t169.254.1.1 # pasta\nnameserver 999.1.1.1\n\
                  nameserver 10.89.0.1\n";
    assert_eq!(name_servers(resolv), [[10, 89, 0, 1], [169, 254, 1, 1]]);
    assert_eq!(name_servers(""), Vec::<[u8; 4]>::new());
    assert_eq!(name_servers("nameserver 127.0.0.11\n"), [[127, 0, 0, 11]]);
    let many: String = (1..=40).map(|n| format!("nameserver 10.0.0.{n}\n")).collect();
    assert_eq!(name_servers(&many).len(), 3, "the resolver reads three at most");
}

#[test]
fn the_gateway_is_the_default_routes() {
    // A route to another network through another gateway comes first: it is not the default.
    let route = "Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT\n\
                 eth0\t0000A8C0\t02005A0A\t0003\t0\t0\t0\t00FFFFFF\t0\t0\t0\n\
                 eth0\t00000000\t01005A0A\t0003\t0\t0\t0\t00000000\t0\t0\t0\n\
                 eth0\t00005A0A\t00000000\t0001\t0\t0\t0\t00FFFFFF\t0\t0\t0\n";
    assert_eq!(default_gateway(route), Some([10, 90, 0, 1]));
    assert_eq!(default_gateway(""), None);
    let no_default = "Iface\tDestination\tGateway\n eth0\t00005A0A\t00000000\t0001\n";
    assert_eq!(default_gateway(no_default), None);
    assert_eq!(default_gateway("Iface\nbad\tzz\tzz\t0003\n"), None);
}

#[test]
fn a_containers_own_networks_are_its_interfaces_its_gateway_and_the_hosts() {
    let own = own_networks(
        &[
            ([10, 89, 0, 5], [255, 255, 255, 0]),
            ([127, 0, 0, 1], [255, 0, 0, 0]),
        ],
        Some([10, 89, 0, 1]),
        &[([203, 0, 113, 7], 24), ([198, 51, 100, 9], 33)],
    );
    assert_eq!(
        own,
        [
            ([10, 89, 0, 0], 24),
            ([127, 0, 0, 0], 8),
            ([10, 89, 0, 1], 32),
            ([203, 0, 113, 0], 24)
        ]
    );
}

/// The container's firewall is the machine's: the internet, DNS to the engine's forwarder and nothing else of the
/// host's or private, whatever range the forwarder sits in. Its own loopback stays its own.
#[test]
fn a_container_reaches_the_internet_and_its_dns_forwarder_on_port_53_only() {
    let forwarder = [169, 254, 1, 1];
    let own = own_networks(
        &[([10, 89, 0, 5], [255, 255, 255, 0])],
        Some([10, 89, 0, 1]),
        &[([203, 0, 113, 7], 24)],
    );
    let rules = policy(&[forwarder], &own).output;
    assert_eq!(out(&rules, [1, 1, 1, 1], TCP, 443, false), Verdict::Accept);
    assert_eq!(out(&rules, forwarder, UDP, 53, false), Verdict::Accept);
    assert_eq!(out(&rules, forwarder, TCP, 53, false), Verdict::Accept);
    assert_eq!(out(&rules, forwarder, TCP, 22, false), Verdict::Drop);
    assert_eq!(
        out(&rules, [169, 254, 169, 254], TCP, 80, false),
        Verdict::Drop,
        "metadata"
    );
    assert_eq!(
        out(&rules, [10, 89, 0, 1], TCP, 8080, false),
        Verdict::Drop,
        "the gateway"
    );
    assert_eq!(
        out(&rules, [203, 0, 113, 9], TCP, 443, false),
        Verdict::Drop,
        "the host's own network"
    );
    assert_eq!(
        out(&rules, [127, 0, 0, 1], TCP, 5432, true),
        Verdict::Accept,
        "its own loopback"
    );
    for (network, _) in BLOCKED {
        assert_eq!(
            out(&rules, *network, TCP, 443, false),
            Verdict::Drop,
            "{network:?}"
        );
    }
}

#[test]
fn a_job_runs_only_under_a_memory_and_process_limit() {
    assert_eq!(limits_in_force("4294967296\n", "4096\n"), Ok((4 << 30, 4096)));
    for (memory, pids) in [
        ("max\n", "4096\n"),
        ("4294967296\n", "max\n"),
        ("", "4096"),
        ("4294967296", "x"),
    ] {
        let refused = limits_in_force(memory, pids).unwrap_err();
        assert!(refused.contains("not in force"), "{refused}");
    }
}

fn status(lines: &[(&str, &str)]) -> String {
    let mut text = String::from("Name:\tsupervisor\nUmask:\t0022\nState:\tR (running)\n");
    for (name, value) in lines {
        text.push_str(&format!("{name}:\t{value}\n"));
    }
    text
}

const LOCKED: &[(&str, &str)] = &[
    ("Uid", "1001\t1001\t1001\t1001"),
    ("Gid", "1001\t1001\t1001\t1001"),
    ("CapInh", "0000000000000000"),
    ("CapPrm", "0000000000000000"),
    ("CapEff", "0000000000000000"),
    ("CapBnd", "0000000000000000"),
    ("CapAmb", "0000000000000000"),
    ("NoNewPrivs", "1"),
    ("Seccomp", "2"),
];

#[test]
fn the_job_starts_only_with_no_capability_left_and_the_filter_on() {
    assert_eq!(locked_down(&status(LOCKED), 1001), Ok(()));
    for (field, value) in [
        ("Uid", "0\t0\t0\t0"),
        ("Uid", "1001\t0\t1001\t1001"),
        ("CapPrm", "0000000000001000"),
        ("CapEff", "0000000000001000"),
        ("CapBnd", "0000000000001000"),
        ("CapAmb", "0000000000000001"),
        ("CapInh", "0000000000000400"),
        ("NoNewPrivs", "0"),
        ("Seccomp", "0"),
    ] {
        let lines: Vec<_> = LOCKED
            .iter()
            .map(|(name, old)| (*name, if *name == field { value } else { old }))
            .collect();
        assert!(locked_down(&status(&lines), 1001).is_err(), "{field}: {value}");
    }
    let missing: Vec<_> = LOCKED
        .iter()
        .copied()
        .filter(|(name, _)| *name != "Seccomp")
        .collect();
    assert!(
        locked_down(&status(&missing), 1001).is_err(),
        "a kernel that does not say"
    );
    assert!(locked_down(&status(LOCKED), 1002).is_err(), "another user");
}

const ERRNO: u32 = 0x0005_0000;
const EPERM: u32 = 1;
const ENOSYS: u32 = 38;

/// The system calls of each architecture a job could make a user namespace with: unshare, clone, clone3.
fn calls(arch: u32) -> (u32, u32, u32) {
    match arch {
        X86_64 => (272, 56, 435),
        I386 => (310, 120, 435),
        AARCH64 => (97, 220, 435),
        ARM => (337, 120, 435),
        _ => unreachable!(),
    }
}

/// What the filter must do: no new user namespace by unshare or clone, no clone3 (whose flags are behind a
/// pointer: the C library falls back to clone), no x32 call, and nothing on an architecture it does not know.
fn expected(arch: u32, nr: u32, flags: u64) -> u32 {
    if ![X86_64, I386, AARCH64, ARM].contains(&arch) {
        return ERRNO | EPERM;
    }
    if arch == X86_64 && nr & X32_BIT != 0 {
        return ERRNO | EPERM;
    }
    let (unshare, clone, clone3) = calls(arch);
    if nr == clone3 {
        ERRNO | ENOSYS
    } else if (nr == unshare || nr == clone) && flags & CLONE_NEWUSER != 0 {
        ERRNO | EPERM
    } else {
        allow()
    }
}

fn data(arch: u32, nr: u32, flags: u64) -> Data {
    Data {
        nr: nr as i32,
        arch,
        ip: 0,
        args: [flags, 0, 0, 0, 0, 0],
    }
}

#[test]
fn no_job_makes_a_user_namespace_on_any_architecture_it_runs() {
    let program = no_user_namespaces();
    for arch in [X86_64, I386, AARCH64, ARM] {
        let (unshare, clone, clone3) = calls(arch);
        let run = |nr, flags| verdict(&program, &data(arch, nr, flags));
        assert_eq!(run(unshare, CLONE_NEWUSER), ERRNO | EPERM, "unshare -U");
        assert_eq!(
            run(unshare, CLONE_NEWUSER | 0x0002_0000),
            ERRNO | EPERM,
            "unshare -Um"
        );
        assert_eq!(run(clone, CLONE_NEWUSER | 0x11), ERRNO | EPERM, "clone");
        assert_eq!(run(unshare, 0x0002_0000), allow(), "a mount namespace alone");
        assert_eq!(run(clone, 0x0011), allow(), "fork through clone");
        assert_eq!(
            run(clone3, 0),
            ERRNO | ENOSYS,
            "clone3: the flags are out of reach"
        );
        assert_eq!(run(0, 0), allow(), "read");
        assert_eq!(
            run(unshare, CLONE_NEWUSER | (1 << 32)),
            ERRNO | EPERM,
            "high bits"
        );
    }
    assert_eq!(
        verdict(&program, &data(X86_64, X32_BIT | 272, CLONE_NEWUSER)),
        ERRNO | EPERM,
        "x32"
    );
    assert_eq!(
        verdict(&program, &data(X86_64, X32_BIT, 0)),
        ERRNO | EPERM,
        "any x32 call"
    );
    assert_eq!(
        verdict(&program, &data(0xc000_00f3, 97, CLONE_NEWUSER)),
        ERRNO | EPERM,
        "riscv64"
    );
    assert!(
        program.len() < 256,
        "every jump of a classic BPF program is a byte"
    );
}

proptest! {
    #[test]
    fn the_filter_decides_any_call_as_specified(
        arch in prop_oneof![Just(X86_64), Just(I386), Just(AARCH64), Just(ARM), any::<u32>()],
        nr in prop_oneof![Just(56u32), Just(97), Just(120), Just(220), Just(272), Just(310), Just(337), Just(435), any::<u32>()],
        flags in any::<u64>(),
    ) {
        let program = no_user_namespaces();
        prop_assert_eq!(verdict(&program, &data(arch, nr, flags)), expected(arch, nr, flags));
    }
}
